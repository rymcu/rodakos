"""Generate main/phone_os/lunar_calendar_data.inc and a reference fixture for the host test.

Source of truth: lunar_python (6tail, MIT), which follows the Purple Mountain Observatory
tables. Run once; the .inc and fixture are checked in. Usage:
  PYTHONPATH=<site with lunar_python> python gen_lunar.py <repo root>
"""
import datetime
import sys
from pathlib import Path

from lunar_python import Lunar, LunarYear, Solar

TERMS = ['小寒', '大寒', '立春', '雨水', '惊蛰', '春分', '清明', '谷雨', '立夏', '小满', '芒种', '夏至',
         '小暑', '大暑', '立秋', '处暑', '白露', '秋分', '寒露', '霜降', '立冬', '小雪', '大雪', '冬至']
FIRST, LAST = 1900, 2100


def year_info(y):
    ly = LunarYear.fromYear(y)
    leap = ly.getLeapMonth()
    big = 0
    leap_big = 0
    for m in ly.getMonths():
        if m.getYear() != y:
            continue
        mi = m.getMonth()
        if mi < 0:
            leap_big = 1 if m.getDayCount() == 30 else 0
        elif m.getDayCount() == 30:
            big |= 1 << (mi - 1)
    first = Lunar.fromYmd(y, 1, 1).getSolar()
    first_doy = datetime.date(first.getYear(), first.getMonth(), first.getDay()).timetuple().tm_yday
    assert first.getYear() == y and first_doy < 64
    # bits 0-11 big months, 12 leap month big, 13-16 leap month (0 none), 17-22 day of year of 正月初一.
    return big | (leap_big << 12) | (leap << 13) | (first_doy << 17)


def term_days(y):
    days = [0] * 24
    d = datetime.date(y, 1, 1)
    while d.year == y:
        jq = Solar.fromYmd(d.year, d.month, d.day).getLunar().getJieQi()
        if jq in TERMS and d.month == TERMS.index(jq) // 2 + 1:
            days[TERMS.index(jq)] = d.day
        d += datetime.timedelta(1)
    assert all(days), y
    return days


def main(root):
    root = Path(root)
    all_terms = [term_days(y) for y in range(FIRST, LAST + 1)]
    base = [min(t[i] for t in all_terms) for i in range(24)]
    assert all(max(t[i] for t in all_terms) - base[i] <= 3 for i in range(24))

    lines = ['// Generated by tests/lunar_calendar/gen_lunar.py from lunar_python (6tail, MIT). Do not edit.',
             f'constexpr int kLunarFirstYear = {FIRST};',
             f'constexpr int kLunarLastYear = {LAST};',
             '// bits 0-11: month n+1 has 30 days; bit 12: leap month has 30 days;',
             '// bits 13-16: leap month number (0 = none); bits 17-22: day of year of the first day.',
             'constexpr uint32_t kLunarYears[] = {']
    words = [year_info(y) for y in range(FIRST, LAST + 1)]
    for i in range(0, len(words), 6):
        lines.append('    ' + ' '.join(f'0x{w:06x},' for w in words[i:i + 6]))
    lines.append('};')
    lines.append('// Earliest day of month for each of the 24 solar terms, 小寒 first.')
    lines.append('constexpr uint8_t kTermBaseDay[24] = {' + ', '.join(map(str, base)) + '};')
    lines.append('// Two bits per term: day = kTermBaseDay[i] + ((word >> (2 * i)) & 3).')
    lines.append('constexpr uint64_t kTermOffsets[] = {')
    packed = []
    for t in all_terms:
        w = 0
        for i in range(24):
            w |= (t[i] - base[i]) << (2 * i)
        packed.append(w)
    for i in range(0, len(packed), 4):
        lines.append('    ' + ' '.join(f'0x{w:012x}ULL,' for w in packed[i:i + 4]))
    lines.append('};')
    (root / 'main/phone_os/lunar_calendar_data.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8')

    # Reference fixture, two sections. "T y d0..d23": the 24 solar term days of year y.
    # "M y m d lunar_year lunar_month leap": the solar date each lunar month starts on, which
    # pins every month length and leap month across the range.
    fixture = []
    for y, t in zip(range(FIRST, LAST + 1), all_terms):
        fixture.append('T %d %s' % (y, ' '.join(map(str, t))))
    for y in range(FIRST, LAST + 1):
        for m in LunarYear.fromYear(y).getMonths():
            if m.getYear() != y:
                continue
            first = Lunar.fromYmd(y, m.getMonth(), 1).getSolar()
            fixture.append('M %d %d %d %d %d %d' % (first.getYear(), first.getMonth(), first.getDay(),
                                                      y, abs(m.getMonth()), 1 if m.getMonth() < 0 else 0))
    (root / 'tests/lunar_calendar/reference.txt').write_text('\n'.join(fixture) + '\n', encoding='utf-8')
    print(len(words), 'years,', len(fixture), 'fixture rows')


if __name__ == '__main__':
    main(sys.argv[1])
