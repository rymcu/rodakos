#!/usr/bin/env python3
"""Generate the RodakOS UI icon fonts from components/rodakos_fonts/icons.json.

Downloads the pinned Iconify package, converts each icon to a TrueType glyph with
tools/icon_preview/iconify_font.py, and runs lv_font_conv once per font size. Outputs:

  components/rodakos_fonts/include/rodakos_icons.h   ICON_* UTF-8 macros
  components/rodakos_fonts/src/<font name>.c         one LVGL font per entry in "fonts"

Names that point at the same Iconify icon share one glyph. Codepoints are assigned in
alphabetical order of the first semantic name, starting at U+F0000 (Supplementary Private Use
Area-A), so they never collide with Montserrat, LV_SYMBOL_* or the CJK subset.

Requires Python with fonttools and skia-pathops, plus Node.js (npm, npx). Downloads and
intermediate files stay in --work-dir.
"""

import argparse
import json
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMPONENT = ROOT / "components" / "rodakos_fonts"
LV_FONT_CONV = "lv_font_conv@1.5.3"

sys.path.insert(0, str(ROOT / "tools" / "icon_preview"))
import iconify_font  # noqa: E402


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--work-dir", type=Path, required=True)
    return parser.parse_args()


def run(command: list[str], cwd: Path) -> None:
    resolved = shutil.which(command[0])
    if resolved is None:
        sys.exit(f"{command[0]} is not on PATH")
    subprocess.run([resolved, *command[1:]], cwd=cwd, check=True)


def fetch_iconify(package: str, version: str, work: Path) -> dict:
    target = work / "iconify"
    icons_json = target / "package" / "icons.json"
    if not icons_json.exists():
        target.mkdir(parents=True, exist_ok=True)
        run(["npm", "pack", f"{package}@{version}", "--silent"], target)
        with tarfile.open(next(target.glob("*.tgz"))) as tar:
            tar.extractall(target, filter="data")
    return iconify_font.load_icon_set(icons_json)


def utf8_literal(codepoint: int) -> str:
    return "".join(f"\\x{byte:02x}" for byte in chr(codepoint).encode("utf-8"))


def main() -> None:
    args = parse_args()
    work = args.work_dir.resolve()
    work.mkdir(parents=True, exist_ok=True)
    config = json.loads((COMPONENT / "icons.json").read_text(encoding="utf-8"))
    source = config["iconify"]
    data = fetch_iconify(source["package"], source["version"], work)

    icons = config["icons"]
    glyph_order = list(dict.fromkeys(icons[name] for name in sorted(icons)))
    codepoints = iconify_font.build_font([(data, name) for name in glyph_order],
                                         work / "rodakos_icons.ttf")
    codepoint_of = {name: codepoints[f"{data['prefix']}:{icons[name]}"] for name in icons}

    for font in config["fonts"]:
        names = sorted(icons) if font["icons"] == "all" else font["icons"]
        missing = [name for name in names if name not in icons]
        if missing:
            sys.exit(f"{font['name']}: unknown icons {missing}")
        ranges = sorted({codepoint_of[name] for name in names})
        run(["npx", "--yes", LV_FONT_CONV, "--no-compress", "--no-prefilter",
             "--force-fast-kern-format", "--font", str(work / "rodakos_icons.ttf"),
             "-r", ",".join(f"0x{codepoint:X}" for codepoint in ranges),
             "--format", "lvgl", "--lv-include", "lvgl.h",
             "--bpp", str(font["bpp"]), "--size", str(font["size"]),
             "--lv-font-name", font["name"],
             "-o", str(COMPONENT / "src" / f"{font['name']}.c")], work)
        problems = iconify_font.check_lvgl_font_placement(
            work / "rodakos_icons.ttf", COMPONENT / "src" / f"{font['name']}.c", font["size"])
        if problems:
            sys.exit(f"{font['name']}: glyph placement lost its side bearing:\n  "
                     + "\n  ".join(problems))
        print(f"{font['name']}: {len(ranges)} glyphs, placement checked")

    width = max(len(name) for name in icons)
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/generate_icon_fonts.py from components/rodakos_fonts/icons.json.",
        "// Do not edit; change icons.json and run the generator.",
        f"// Glyphs: {source['upstream']}.",
        "// Every icon is in rodakos_icons_20_4. The desktop subset is also in rodakos_icons_30_4.",
        "",
    ]
    for name in sorted(icons):
        lines.append(f'#define ICON_{name.ljust(width)} "{utf8_literal(codepoint_of[name])}"'
                     f"  // ion:{icons[name]}")
    (COMPONENT / "include" / "rodakos_icons.h").write_text("\n".join(lines) + "\n",
                                                          encoding="utf-8", newline="\n")
    print(f"rodakos_icons.h: {len(icons)} names, {len(glyph_order)} glyphs")


if __name__ == "__main__":
    main()
